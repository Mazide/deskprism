"""Rasterize upstream dot glyphs, resize to TFT, pack lossless RGB565 RLE.
Run export_original.cjs first. Requires Pillow. No network during generation.
"""
import json
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parent.parent
data = json.loads(Path('/tmp/prism-original-frames.json').read_text())
palette = data['palette']
packed = bytearray()
offsets = [0]
previews = []
for frame in data['frames']:
    image = Image.new('RGB', (800, 400))
    draw = ImageDraw.Draw(image)
    # Raster equivalents of the original halftone glyphs ·, •, ●.
    for k, (step, color) in enumerate(zip(frame['dots'], frame['color'])):
        if not step:
            continue
        x, y = (k % 200) * 4, (k // 200) * 4
        radius = (0, .7, 1.2, 1.8)[step]
        draw.ellipse((x+2-radius, y+2-radius, x+2+radius, y+2+radius), fill=palette[color])
    image = image.resize((240, 120), Image.Resampling.LANCZOS)
    pixels = [((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
              for r, g, b in image.getdata()]
    i = 0
    while i < len(pixels):
        count = 1
        while i + count < len(pixels) and count < 255 and pixels[i+count] == pixels[i]:
            count += 1
        p = pixels[i]
        packed.extend((count, p & 255, p >> 8))
        i += count
    offsets.append(len(packed))
    # Preview actual quantized firmware pixels, not the pre-quantized image.
    decoded = Image.new('RGB', (240, 120))
    decoded.putdata([(((p>>11)&31)*255//31, ((p>>5)&63)*255//63, (p&31)*255//31) for p in pixels])
    canvas = Image.new('RGB', (240, 240))
    canvas.paste(decoded, (0, 60))
    previews.append(canvas.resize((480, 480), Image.Resampling.NEAREST))

header = ['// Generated by tools/pack_original.py; upstream MIT license in THIRD_PARTY_NOTICES.txt.',
          '#pragma once', '#include <stdint.h>', '#include <pgmspace.h>', 'namespace prism {',
          'constexpr unsigned frameCount = 90;',
          'static const uint32_t frameOffsets[] PROGMEM = {' + ','.join(map(str, offsets)) + '};',
          'static const uint8_t frameData[] PROGMEM = {']
header.extend(','.join(map(str, packed[i:i+48])) + ',' for i in range(0, len(packed), 48))
header.extend(['};', '} // namespace prism'])
(ROOT / 'black_prism_frames.h').write_text('\n'.join(header)+'\n')
(ROOT / 'preview').mkdir(exist_ok=True)
previews[15].save(ROOT / 'preview/black-prism.png')
previews[0].save(ROOT / 'preview/black-prism.gif', save_all=True, append_images=previews[1:],
                 duration=[67,67,66]*30, loop=0)
print(f'{len(packed):,} bytes in Flash, {len(previews)} frames')
